#!/usr/bin/env python3
"""Inventory the SFX kit: name, type, length, peak, and the timing points the SFX design pass needs.

    sfx_index.py            -> library/sfx/INDEX.md + library/sfx/timing.json

timing.json per sound: dur (s), peak_db (dBFS), peak_t (s, loudest 10 ms window), onset_t (first sample within
30 dB of the peak), tail_t (last sample within 30 dB of the peak). The design pass ends a riser on a cut with
peak_t (the swell's top), not with the file's end (most risers carry a few hundred ms of decay after the top).

SFX_DIR overrides the folder (default library/sfx). No audio is in git: a deployment restores the licensed sounds outside
it (library/SOURCES.md), so on a clean checkout this writes an empty index; ids in the manifest whose file is not on disk are
skipped. Run it after adding a sound and copy the measured dur / peak_db into that id's manifest entry. Needs ffmpeg on PATH
and numpy. The design-pass family names in the generated INDEX.md are the ids lib/premium.mjs asks for; a restored kit may
not have a file for every one of them.
"""
import json, os, subprocess
from pathlib import Path
import numpy as np

SFX = Path(os.environ.get("SFX_DIR") or Path(__file__).resolve().parent.parent / "library" / "sfx")
SR = 48000


def load(f):
    raw = subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-i", str(f), "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True).stdout
    return np.frombuffer(raw, np.float32)


def main():
    man = json.loads((SFX / "manifest.json").read_text(encoding="utf-8"))
    timing, rows = {}, []
    for sid, m in sorted(man.items()):
        f = SFX / m["file"]
        if not f.exists():
            continue
        x = np.abs(load(f))
        if not len(x):
            continue
        win = SR // 100
        env = np.array([x[i:i + win].max() for i in range(0, len(x), win)])
        pk = float(env.max()) or 1e-9
        db = 20 * np.log10(pk)
        loud = np.where(env >= pk * 10 ** (-30 / 20))[0]
        t = {"dur": round(len(x) / SR, 3), "peak_db": round(db, 1), "peak_t": round(float(env.argmax()) * win / SR, 3),
             "onset_t": round(float(loud[0]) * win / SR, 3), "tail_t": round(float(loud[-1] + 1) * win / SR, 3)}
        timing[sid] = t
        rows.append((sid, m.get("role", "?"), ", ".join(m.get("tags", [])), t))
    (SFX / "timing.json").write_text(json.dumps(timing, indent=1) + "\n", encoding="utf-8")
    out = ["# SFX library index", "",
           "Generated by `scripts/sfx_index.py` (re-run after adding sounds). Files are peak-normalized to about -1 dBFS;",
           "the build sets each hit's level relative to the voice by `role` (ui -14, whoosh -12, impact -8, meme -3 dB vs voice p95).",
           "peak_t = loudest 10 ms (where a riser tops out), onset/tail = first/last moment within 30 dB of the peak.", "",
           f"{len(rows)} sounds.", "",
           "| name | type (role) | tags | length s | peak dBFS | peak at s | onset s | tail s |", "|---|---|---|---|---|---|---|---|"]
    for sid, role, tags, t in rows:
        out.append(f"| {sid} | {role} | {tags} | {t['dur']} | {t['peak_db']} | {t['peak_t']} | {t['onset_t']} | {t['tail_t']} |")
    out += ["", "## Design-pass families (lib/premium.mjs)", "",
            "- risers (end on a hard cut): riser-1, cinematic-rumble-riser, cinematic-drone-swell",
            "- hits (on the cut): cinematic-cine-hit, impact-1, impact-2, cinematic-deep-boom",
            "- tails (after the hit, short): whoosh-cine, cinematic-film-flash",
            "- soft whoosh (text in): pop-whoosh-light, whoosh-cine, zoom-sweep-small",
            "- ticks (word pops): tick-1, click-1",
            "- swish (punch-ins / whips): zoom-sweep-short, zoom-sweep-small, burn-whoosh-fast", ""]
    (SFX / "INDEX.md").write_text("\n".join(out), encoding="utf-8")
    print(f"{len(rows)} sounds -> {SFX / 'INDEX.md'}")


if __name__ == "__main__":
    main()
